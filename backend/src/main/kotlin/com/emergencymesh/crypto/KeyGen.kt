package com.emergencymesh.crypto

import com.emergencymesh.proto.EmergencyPayload
import java.io.File
import java.util.Base64

/**
 * `./gradlew genKeys`: run once, before the demo.
 *
 *  - backend/secrets/mesh-keys.properties : PRIVATE key, git-ignored, never
 *    leaves this machine
 *  - mesh_app/lib/crypto/backend_public_key.dart : PUBLIC key, compiled into
 *    the app. Rebuild and reinstall the app afterwards.
 *  - mesh_app/lib/crypto/hq_signing_key.dart : PUBLIC Ed25519 key phones use
 *    to verify HQ receipts and alerts. Derived from the private key, so
 *    re-running genKeys on an existing key only refreshes this file.
 *
 * Refuses to overwrite an existing key: messages sealed for the old key
 * (still circulating on phones) could never be opened again.
 */
fun main(args: Array<String>) {
	val keyFile = File("secrets/mesh-keys.properties")
	val force = "--force" in args
	if (keyFile.exists() && !force) {
		println("Key already exists: ${keyFile.absolutePath}")
		println("Use --force to replace it (phones must then be reinstalled).")
		val line = keyFile.readLines().first { it.startsWith("mesh.crypto.private-key=") }
		writeSigningKey(Base64.getDecoder().decode(line.substringAfter('=').trim()))
		return
	}
	val (pk, sk) = Sodium.newKeyPair()
	val b64 = Base64.getEncoder()

	keyFile.parentFile.mkdirs()
	keyFile.writeText(
		"# Backend sealed-box keypair (FR-3). PRIVATE: do not commit or share.\n" +
			"mesh.crypto.private-key=${b64.encodeToString(sk)}\n",
	)

	val dart = File("../mesh_app/lib/crypto/backend_public_key.dart")
	dart.writeText(
		"""
		|// Generated by `./gradlew genKeys` in backend/. Do not edit by hand.
		|//
		|// The backend's X25519 public key (FR-3). Phones seal emergency content
		|// with it; only the backend's private key (never in this app) can open it.
		|const String backendPublicKeyBase64 = '${b64.encodeToString(pk)}';
		|
		""".trimMargin(),
	)

	// A sample upload body sealed for this key, for Postman / requests.http.
	val sample = EmergencyPayload.newBuilder()
		.setLatitude(13.0827).setLongitude(80.2707).setNote("Leg injury, 2 people").build()
	val sealed = b64.encodeToString(Sodium.seal(sample.toByteArray(), pk))
	File("secrets/sample-sealed-payload.txt").writeText(sealed + "\n")

	writeSigningKey(sk)
	println("Private key -> ${keyFile.absolutePath}")
	println("Public key  -> ${dart.canonicalPath}")
	println("Public key: ${b64.encodeToString(pk)}")
	println("Sample sealedPayload for Postman -> secrets/sample-sealed-payload.txt")
	println("Now rebuild and reinstall the app on every phone.")
}

/** Writes the HQ notice-signing public key (derived from [secretKey]) into the app's source. */
private fun writeSigningKey(secretKey: ByteArray) {
	val (signPk, _) = Sodium.signingKeyPairFrom(secretKey)
	val dart = File("../mesh_app/lib/crypto/hq_signing_key.dart")
	dart.writeText(
		"""
		|// Generated by `./gradlew genKeys` in backend/. Do not edit by hand.
		|//
		|// HQ's Ed25519 public key. Phones verify every receipt and alert against it
		|// and drop anything not signed by HQ's private key (never in this app).
		|const String hqSigningPublicKeyBase64 = '${Base64.getEncoder().encodeToString(signPk)}';
		|
		""".trimMargin(),
	)
	println("Signing key -> ${dart.canonicalPath}")
}
